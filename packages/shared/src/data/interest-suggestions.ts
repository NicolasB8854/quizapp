/**
 * Kombiniert Katalog-Tags (bereits genutzte Feintags aus Fragen) mit
 * unseren kuratierten Vorschlägen. Katalog-Tags stehen vorne, damit
 * bereits vorhandene Tags Priorität haben.
 *
 * Dedupliziert, Case-insensitive. Bereits gewählte Tags werden ausgefiltert.
 */
export function getInterestSuggestionsForTopic(
  topic: Topic,
  catalogTagsForTopic: readonly string[],
  alreadyChosen: readonly string[],
): string[] {
  const chosenLower = new Set(alreadyChosen.map((t) => t.toLowerCase().trim()))
  const seen = new Set<string>()
  const out: string[] = []

  const push = (raw: string) => {
    const t = raw.trim()
    if (!t) return
    const lower = t.toLowerCase()
    if (chosenLower.has(lower)) return
    if (seen.has(lower)) return
    seen.add(lower)
    out.push(t)
  }

  for (const t of catalogTagsForTopic) push(t)
  for (const t of INTEREST_SUGGESTIONS[topic] ?? []) push(t)
  return out
}
